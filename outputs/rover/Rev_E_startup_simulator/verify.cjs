const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const page = fs.readFileSync(path.join(__dirname, "startup-simulator.html"), "utf8");
const code = page.match(/<script id="model">([\s\S]*?)<\/script>/)[1];
const model = vm.runInNewContext(code + "\nmodel");
const defaults = {cell:4200, charger:4230, drop:0, wake:700, uv:2600, release:400, pulse:5941};
const next = (s, event, options={}) => model.step(s, event, {...defaults,...options});
const fresh = () => next(model.initial(), "insert");
assert.equal(fresh().mode, "shutdown");
assert.equal(next(fresh(), "usb").pack, 4230);
assert.equal(next(fresh(), "usb").mode, "shutdown");
assert.equal(next(fresh(), "usb", {cell:3500,charger:4200}).mode, "shutdown");
assert.equal(next(fresh(), "usb", {cell:3100,drop:300}).mode, "normal");
assert.equal(next(fresh(), "usb", {cell:3100,drop:500}).mode, "shutdown");
assert.equal(next(fresh(), "pulse", {cell:2600}).mode, "shutdown");
const awake = next(fresh(), "pulse");
assert.equal(awake.mode, "normal");
const normal = next(awake, "restore");
assert.equal(normal.pack, 4200);
const tripped = next(normal, "trip");
assert.equal(tripped.mode, "fault");
assert.equal(next(tripped, "restore").mode, "fault");
assert.equal(next(tripped, "clear").mode, "normal");
const retry = next(tripped, "pulse");
assert.equal(retry.mode, "normal");
assert.equal(retry.unsafe, true);
assert.equal(next(retry, "restore").mode, "fault");
assert.equal(next(model.initial(), "pulse").mode, "absent");
assert.equal(model.recoveryTest(0).released, false);
assert.equal(model.recoveryTest(10).pack, 0.3);
assert.equal(model.recoveryTest(10).released, false);
assert.equal(model.recoveryTest(1000 / 30).released, false);
assert.equal(model.recoveryTest(34).released, true);
assert.equal(model.recoveryTest(100).pack, 3);
assert.equal(model.recoveryTest(0, 30000).released, false);
assert.equal(model.recoveryTest(1, 0).released, false);
assert.equal(model.recoveryTest(1, 970).released, false);
assert.equal(model.recoveryTest(1, 971).released, true);
assert.equal(model.recoveryTest(1, 971).requiredCurrent, 1000);
const split = (state, event, options={}) => model.splitStep(state, event, {cellHealthy:true, ...options});
const ready = split(split(null,"insert"),"wake");
assert.equal(ready.paths.logic, "battery");
assert.equal(ready.paths.motors, false);
const driving = split(ready,"arm");
assert.equal(driving.paths.motors, true);
const trippedSplit = split(driving,"trip");
assert.equal(trippedSplit.paths.batteryToLoad, false);
const usbSplit = split(trippedSplit,"usb");
assert.equal(usbSplit.paths.logic, "USB");
assert.equal(usbSplit.paths.charge, true);
assert.equal(usbSplit.paths.batteryToLoad, false);
assert.equal(split(usbSplit,"arm").paths.motors, false);
assert.equal(split(split(usbSplit,"removeUsb"),"arm").paths.batteryToLoad, false);
const clearedSplit = split(split(usbSplit,"clear"),"removeUsb");
assert.equal(clearedSplit.paths.batteryToLoad, false);
assert.equal(split(clearedSplit,"reset").paths.motors, false);
assert.equal(split(split(null,"insert",{cellHealthy:false}),"wake",{cellHealthy:false}).paths.batteryToLoad,false);
assert.equal(split(driving,"usb").paths.motors, false);
assert.equal(split(null,"usb").paths.charge, false);
let rearm = model.hardwareRearm(null,{resetReleased:false,button:false});
assert.equal(rearm.enabled,false);
rearm = model.hardwareRearm(rearm,{resetReleased:false,button:true});
assert.equal(rearm.enabled,false);
rearm = model.hardwareRearm(rearm,{resetReleased:true,button:true});
assert.equal(rearm.enabled,false);
rearm = model.hardwareRearm(rearm,{resetReleased:true,button:false});
assert.equal(rearm.enabled,false);
rearm = model.hardwareRearm(rearm,{resetReleased:true,button:true});
assert.equal(rearm.enabled,true);
rearm = model.hardwareRearm(rearm,{resetReleased:false,button:true});
assert.equal(rearm.enabled,false);
assert.equal(model.hardwareRearm(rearm,{resetReleased:true,button:true}).enabled,false);
console.log("47 startup, fault-recovery, isolation and rearm assertions passed.");
